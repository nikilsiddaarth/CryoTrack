-- 1. Display all pharmaceutical products
SELECT *
FROM PHARMACEUTICAL_PRODUCT;

-- 2. Products with manufacturer details
SELECT P.PRODUCT_ID, P.PRODUCT_NAME, P.GENERIC_NAME,
       M.MANUFACTURER_NAME, P.REGULATORY_STATUS
FROM PHARMACEUTICAL_PRODUCT P
JOIN MANUFACTURER M
ON M.MANUFACTURER_ID = P.MANUFACTURER_ID;

-- 3. Approved products
SELECT PRODUCT_ID, PRODUCT_NAME, GENERIC_NAME, DOSAGE_FORM
FROM PHARMACEUTICAL_PRODUCT
WHERE REGULATORY_STATUS = 'Approved';

-- 4. Product batches with product names and expiry dates
SELECT B.BATCH_ID, B.BATCH_NUMBER, P.PRODUCT_NAME,
       B.MANUFACTURING_DATE, B.EXPIRY_DATE, B.QUALITY_STATUS
FROM PRODUCT_BATCH B
JOIN PHARMACEUTICAL_PRODUCT P
ON P.PRODUCT_ID = B.PRODUCT_ID
ORDER BY B.EXPIRY_DATE;

-- 5. Batches expiring within the next 180 days
SELECT BATCH_ID, BATCH_NUMBER, EXPIRY_DATE, BATCH_STATUS
FROM PRODUCT_BATCH
WHERE EXPIRY_DATE BETWEEN SYSDATE AND SYSDATE + 180
ORDER BY EXPIRY_DATE;

-- 6. Quality tests for each batch
SELECT P.PRODUCT_NAME, B.BATCH_NUMBER, Q.TEST_TYPE,
       Q.TEST_RESULT, Q.TEST_DATE, Q.TESTED_BY
FROM QUALITY_TEST Q
JOIN PRODUCT_BATCH B ON B.BATCH_ID = Q.BATCH_ID
JOIN PHARMACEUTICAL_PRODUCT P ON P.PRODUCT_ID = B.PRODUCT_ID
ORDER BY Q.TEST_DATE DESC;

-- 7. Inventory with product, batch, storage unit and warehouse
SELECT I.INVENTORY_ID, P.PRODUCT_NAME, B.BATCH_NUMBER,
       I.QUANTITY_AVAILABLE, I.QUANTITY_RESERVED,
       SU.UNIT_NAME, W.WAREHOUSE_NAME
FROM INVENTORY I
JOIN PRODUCT_BATCH B ON B.BATCH_ID = I.BATCH_ID
JOIN PHARMACEUTICAL_PRODUCT P ON P.PRODUCT_ID = B.PRODUCT_ID
JOIN STORAGE_UNIT SU ON SU.STORAGE_UNIT_ID = I.STORAGE_UNIT_ID
JOIN WAREHOUSE W ON W.WAREHOUSE_ID = SU.WAREHOUSE_ID;

-- 8. Total available inventory by warehouse
SELECT W.WAREHOUSE_NAME,
       SUM(I.QUANTITY_AVAILABLE) AS TOTAL_AVAILABLE
FROM WAREHOUSE W
JOIN STORAGE_UNIT SU ON SU.WAREHOUSE_ID = W.WAREHOUSE_ID
JOIN INVENTORY I ON I.STORAGE_UNIT_ID = SU.STORAGE_UNIT_ID
GROUP BY W.WAREHOUSE_NAME
ORDER BY TOTAL_AVAILABLE DESC;

-- 9. Warehouses having more than one storage unit
SELECT W.WAREHOUSE_NAME,
       COUNT(SU.STORAGE_UNIT_ID) AS UNIT_COUNT
FROM WAREHOUSE W
JOIN STORAGE_UNIT SU ON SU.WAREHOUSE_ID = W.WAREHOUSE_ID
GROUP BY W.WAREHOUSE_NAME
HAVING COUNT(SU.STORAGE_UNIT_ID) > 1;

-- 10. Inventory transactions
SELECT TRANSACTION_ID, INVENTORY_ID, TRANSACTION_TYPE,
       QUANTITY, TRANSACTION_DATE, PERFORMED_BY
FROM INVENTORY_TRANSACTION
ORDER BY TRANSACTION_DATE DESC;

-- 11. Shipment details with route information
SELECT S.SHIPMENT_ID, S.SHIPMENT_DATE, S.SHIPMENT_STATUS,
       S.PRIORITY_LEVEL, R.ORIGIN, R.DESTINATION, R.TOTAL_DISTANCE
FROM SHIPMENT S
JOIN ROUTE R ON R.ROUTE_ID = S.ROUTE_ID;

-- 12. Shipment contents with batch and product information
SELECT SI.SHIPMENT_ID, B.BATCH_NUMBER, P.PRODUCT_NAME,
       SI.QUANTITY, SI.PACKAGING_TYPE
FROM SHIPMENT_ITEM SI
JOIN PRODUCT_BATCH B ON B.BATCH_ID = SI.BATCH_ID
JOIN PHARMACEUTICAL_PRODUCT P ON P.PRODUCT_ID = B.PRODUCT_ID
ORDER BY SI.SHIPMENT_ID;

-- 13. Vehicle and driver assignments
SELECT VA.ASSIGNMENT_ID, S.SHIPMENT_ID,
       V.REGISTRATION_NUMBER, D.DRIVER_NAME,
       VA.ASSIGNMENT_STATUS
FROM VEHICLE_ASSIGNMENT VA
JOIN SHIPMENT S ON S.SHIPMENT_ID = VA.SHIPMENT_ID
JOIN VEHICLE V ON V.VEHICLE_ID = VA.VEHICLE_ID
JOIN DRIVER D ON D.DRIVER_ID = VA.DRIVER_ID;

-- 14. Route stops in planned sequence
SELECT R.ROUTE_ID, R.ORIGIN, R.DESTINATION,
       RS.STOP_NAME, RS.STOP_TYPE, RS.SEQUENCE_NUMBER
FROM ROUTE R
JOIN ROUTE_STOP RS ON RS.ROUTE_ID = R.ROUTE_ID
ORDER BY R.ROUTE_ID, RS.SEQUENCE_NUMBER;

-- 15. Sensor readings with vehicle information
SELECT V.REGISTRATION_NUMBER, S.SENSOR_ID, S.SERIAL_NUMBER,
       SR.READING_TIMESTAMP, SR.TEMPERATURE,
       SR.HUMIDITY, SR.BATTERY_LEVEL
FROM SENSOR_READING SR
JOIN IOT_SENSOR S ON S.SENSOR_ID = SR.SENSOR_ID
JOIN VEHICLE V ON V.VEHICLE_ID = S.VEHICLE_ID
ORDER BY SR.READING_TIMESTAMP DESC;

-- 16. Temperature alerts
SELECT ALERT_ID, ALERT_TIME, ALERT_TYPE,
       RECORDED_TEMPERATURE, EXPECTED_MIN, EXPECTED_MAX,
       SEVERITY, ALERT_STATUS, SHIPMENT_ID
FROM TEMPERATURE_ALERT
ORDER BY ALERT_TIME DESC;

-- 17. Open high-severity temperature alerts
SELECT ALERT_ID, SHIPMENT_ID, SENSOR_ID,
       ALERT_TIME, RECORDED_TEMPERATURE, SEVERITY
FROM TEMPERATURE_ALERT
WHERE ALERT_STATUS = 'Open'
AND SEVERITY = 'High';

-- 18. Cold-chain incidents with related alert details
SELECT C.INCIDENT_ID, C.INCIDENT_TYPE, C.INCIDENT_DATE,
       C.SEVERITY, C.RESOLUTION_STATUS,
       A.ALERT_ID, C.SHIPMENT_ID
FROM COLD_CHAIN_INCIDENT C
JOIN TEMPERATURE_ALERT A
ON A.ALERT_ID = C.ALERT_ID;

-- 19. Unresolved cold-chain incidents
SELECT INCIDENT_ID, SHIPMENT_ID, INCIDENT_TYPE,
       SEVERITY, DESCRIPTION, RESOLUTION_STATUS
FROM COLD_CHAIN_INCIDENT
WHERE RESOLUTION_STATUS <> 'Resolved'
OR RESOLUTION_STATUS IS NULL;

-- 20. Deliveries with healthcare-facility names
SELECT D.DELIVERY_ID, D.SHIPMENT_ID, H.FACILITY_NAME,
       D.DELIVERY_DATE, D.DELIVERY_STATUS,
       D.QUANTITY_RECEIVED, D.QUANTITY_DAMAGED
FROM DELIVERY D
JOIN HEALTHCARE_FACILITY H
ON H.FACILITY_ID = D.FACILITY_ID;

-- 21. Shipment count by status
SELECT SHIPMENT_STATUS, COUNT(*) AS SHIPMENT_COUNT
FROM SHIPMENT
GROUP BY SHIPMENT_STATUS;

-- 22. Temperature-alert count by severity
SELECT SEVERITY, COUNT(*) AS ALERT_COUNT
FROM TEMPERATURE_ALERT
GROUP BY SEVERITY;

-- 23. Temperature statistics by sensor
SELECT SENSOR_ID,
       ROUND(AVG(TEMPERATURE), 2) AS AVG_TEMPERATURE,
       MIN(TEMPERATURE) AS MIN_TEMPERATURE,
       MAX(TEMPERATURE) AS MAX_TEMPERATURE
FROM SENSOR_READING
GROUP BY SENSOR_ID;

-- 24. Number of batches for each product
SELECT P.PRODUCT_ID, P.PRODUCT_NAME,
       COUNT(B.BATCH_ID) AS BATCH_COUNT
FROM PHARMACEUTICAL_PRODUCT P
LEFT JOIN PRODUCT_BATCH B
ON B.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME;

-- 25. Products having at least one batch
SELECT P.PRODUCT_ID, P.PRODUCT_NAME
FROM PHARMACEUTICAL_PRODUCT P
WHERE EXISTS (
    SELECT 1
    FROM PRODUCT_BATCH B
    WHERE B.PRODUCT_ID = P.PRODUCT_ID
);

-- 26. Earliest-expiring batch for each product
SELECT B.BATCH_NUMBER, B.PRODUCT_ID, B.EXPIRY_DATE
FROM PRODUCT_BATCH B
WHERE B.EXPIRY_DATE = (
    SELECT MIN(B2.EXPIRY_DATE)
    FROM PRODUCT_BATCH B2
    WHERE B2.PRODUCT_ID = B.PRODUCT_ID
);

-- 27. Products having above-average batch counts
SELECT PRODUCT_ID, COUNT(*) AS BATCH_COUNT
FROM PRODUCT_BATCH
GROUP BY PRODUCT_ID
HAVING COUNT(*) > (
    SELECT AVG(BATCH_COUNT)
    FROM (
        SELECT COUNT(*) AS BATCH_COUNT
        FROM PRODUCT_BATCH
        GROUP BY PRODUCT_ID
    )
);

-- 28. Product storage conditions
SELECT P.PRODUCT_NAME, SC.MINIMUM_TEMPERATURE,
       SC.MAXIMUM_TEMPERATURE, SC.MINIMUM_HUMIDITY,
       SC.MAXIMUM_HUMIDITY, SC.STORAGE_INSTRUCTIONS
FROM PHARMACEUTICAL_PRODUCT P
JOIN STORAGE_CONDITION SC
ON SC.PRODUCT_ID = P.PRODUCT_ID;

-- 29. Available and reserved stock by product
SELECT P.PRODUCT_ID, P.PRODUCT_NAME,
       SUM(I.QUANTITY_AVAILABLE) AS AVAILABLE_STOCK,
       SUM(I.QUANTITY_RESERVED) AS RESERVED_STOCK
FROM PHARMACEUTICAL_PRODUCT P
JOIN PRODUCT_BATCH B ON B.PRODUCT_ID = P.PRODUCT_ID
JOIN INVENTORY I ON I.BATCH_ID = B.BATCH_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME;

-- 30. Vehicles and number of sensors
SELECT V.VEHICLE_ID, V.REGISTRATION_NUMBER,
       COUNT(S.SENSOR_ID) AS SENSOR_COUNT
FROM VEHICLE V
LEFT JOIN IOT_SENSOR S
ON S.VEHICLE_ID = V.VEHICLE_ID
GROUP BY V.VEHICLE_ID, V.REGISTRATION_NUMBER;

-- 31. Healthcare facilities and delivery totals
SELECT H.FACILITY_NAME,
       COUNT(D.DELIVERY_ID) AS DELIVERY_COUNT,
       SUM(D.QUANTITY_RECEIVED) AS TOTAL_RECEIVED
FROM HEALTHCARE_FACILITY H
LEFT JOIN DELIVERY D
ON D.FACILITY_ID = H.FACILITY_ID
GROUP BY H.FACILITY_NAME;

-- 32. Display all tables
SELECT TABLE_NAME
FROM USER_TABLES
ORDER BY TABLE_NAME;

-- 33. Display constraints
SELECT TABLE_NAME, CONSTRAINT_NAME,
       CONSTRAINT_TYPE, STATUS
FROM USER_CONSTRAINTS
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;

-- 34. Display indexes
SELECT TABLE_NAME, INDEX_NAME, UNIQUENESS
FROM USER_INDEXES
ORDER BY TABLE_NAME, INDEX_NAME;

