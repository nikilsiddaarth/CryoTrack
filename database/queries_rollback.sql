SELECT * FROM PHARMACEUTICAL_PRODUCT;

SELECT PRODUCT_NAME, GENERIC_NAME, DOSAGE_FORM, REGULATORY_STATUS
FROM PHARMACEUTICAL_PRODUCT
WHERE REGULATORY_STATUS = 'Approved';

SELECT *
FROM PRODUCT_BATCH
WHERE EXPIRY_DATE < SYSDATE + 180
ORDER BY EXPIRY_DATE;

SELECT PRODUCT_NAME, SHELF_LIFE_DAYS
FROM PHARMACEUTICAL_PRODUCT
ORDER BY SHELF_LIFE_DAYS DESC;

SELECT P.PRODUCT_NAME, M.MANUFACTURER_NAME
FROM PHARMACEUTICAL_PRODUCT P
JOIN MANUFACTURER M
ON P.MANUFACTURER_ID = M.MANUFACTURER_ID;

SELECT B.BATCH_NUMBER, P.PRODUCT_NAME, B.MANUFACTURING_DATE, B.EXPIRY_DATE, B.QUALITY_STATUS
FROM PRODUCT_BATCH B
JOIN PHARMACEUTICAL_PRODUCT P
ON B.PRODUCT_ID = P.PRODUCT_ID;

SELECT B.BATCH_NUMBER, P.PRODUCT_NAME, Q.TEST_TYPE, Q.TEST_RESULT, Q.TESTED_BY
FROM PRODUCT_BATCH B
JOIN PHARMACEUTICAL_PRODUCT P
ON B.PRODUCT_ID = P.PRODUCT_ID
JOIN QUALITY_TEST Q
ON B.BATCH_ID = Q.BATCH_ID;

SELECT I.INVENTORY_ID, B.BATCH_NUMBER, P.PRODUCT_NAME,
       I.QUANTITY_AVAILABLE, I.QUANTITY_RESERVED,
       S.UNIT_NAME, W.WAREHOUSE_NAME
FROM INVENTORY I
JOIN PRODUCT_BATCH B ON I.BATCH_ID = B.BATCH_ID
JOIN PHARMACEUTICAL_PRODUCT P ON B.PRODUCT_ID = P.PRODUCT_ID
JOIN STORAGE_UNIT S ON I.STORAGE_UNIT_ID = S.STORAGE_UNIT_ID
JOIN WAREHOUSE W ON S.WAREHOUSE_ID = W.WAREHOUSE_ID;

SELECT W.WAREHOUSE_NAME, SUM(I.QUANTITY_AVAILABLE) AS TOTAL_STOCK
FROM WAREHOUSE W
JOIN STORAGE_UNIT S ON W.WAREHOUSE_ID = S.WAREHOUSE_ID
JOIN INVENTORY I ON S.STORAGE_UNIT_ID = I.STORAGE_UNIT_ID
GROUP BY W.WAREHOUSE_NAME;

SELECT W.WAREHOUSE_NAME, COUNT(S.STORAGE_UNIT_ID) AS TOTAL_STORAGE_UNITS
FROM WAREHOUSE W
JOIN STORAGE_UNIT S ON W.WAREHOUSE_ID = S.WAREHOUSE_ID
GROUP BY W.WAREHOUSE_NAME
HAVING COUNT(S.STORAGE_UNIT_ID) > 1;

SELECT SH.SHIPMENT_ID, SH.SHIPMENT_DATE, SH.SHIPMENT_STATUS,
       R.ORIGIN, R.DESTINATION, R.TOTAL_DISTANCE
FROM SHIPMENT SH
JOIN ROUTE R ON SH.ROUTE_ID = R.ROUTE_ID;

SELECT SI.SHIPMENT_ID, B.BATCH_NUMBER, P.PRODUCT_NAME,
       SI.QUANTITY, SI.PACKAGING_TYPE
FROM SHIPMENT_ITEM SI
JOIN PRODUCT_BATCH B ON SI.BATCH_ID = B.BATCH_ID
JOIN PHARMACEUTICAL_PRODUCT P ON B.PRODUCT_ID = P.PRODUCT_ID;

SELECT SH.SHIPMENT_ID, V.REGISTRATION_NUMBER,
       D.DRIVER_NAME, VA.ASSIGNMENT_STATUS
FROM VEHICLE_ASSIGNMENT VA
JOIN SHIPMENT SH ON VA.SHIPMENT_ID = SH.SHIPMENT_ID
JOIN VEHICLE V ON VA.VEHICLE_ID = V.VEHICLE_ID
JOIN DRIVER D ON VA.DRIVER_ID = D.DRIVER_ID;

SELECT S.SENSOR_ID, S.SERIAL_NUMBER, V.REGISTRATION_NUMBER,
       SR.TEMPERATURE, SR.HUMIDITY, SR.READING_TIMESTAMP
FROM IOT_SENSOR S
JOIN VEHICLE V ON S.VEHICLE_ID = V.VEHICLE_ID
JOIN SENSOR_READING SR ON S.SENSOR_ID = SR.SENSOR_ID
ORDER BY SR.READING_TIMESTAMP DESC;

SELECT TA.ALERT_ID, TA.ALERT_TYPE, TA.RECORDED_TEMPERATURE,
       TA.EXPECTED_MIN, TA.EXPECTED_MAX, TA.SEVERITY,
       TA.ALERT_STATUS, SH.SHIPMENT_ID
FROM TEMPERATURE_ALERT TA
JOIN SHIPMENT SH ON TA.SHIPMENT_ID = SH.SHIPMENT_ID
ORDER BY TA.ALERT_TIME DESC;

SELECT C.INCIDENT_ID, C.INCIDENT_TYPE, C.SEVERITY,
       C.DESCRIPTION, C.RESOLUTION_STATUS,
       TA.ALERT_ID, SH.SHIPMENT_ID
FROM COLD_CHAIN_INCIDENT C
JOIN TEMPERATURE_ALERT TA ON C.ALERT_ID = TA.ALERT_ID
JOIN SHIPMENT SH ON C.SHIPMENT_ID = SH.SHIPMENT_ID;

SELECT D.DELIVERY_ID, SH.SHIPMENT_ID,
       HF.FACILITY_NAME, D.DELIVERY_STATUS,
       D.QUANTITY_RECEIVED, D.QUANTITY_DAMAGED
FROM DELIVERY D
JOIN SHIPMENT SH ON D.SHIPMENT_ID = SH.SHIPMENT_ID
JOIN HEALTHCARE_FACILITY HF ON D.FACILITY_ID = HF.FACILITY_ID;

SELECT PRODUCT_ID, COUNT(*) AS TOTAL_BATCHES
FROM PRODUCT_BATCH
GROUP BY PRODUCT_ID;

SELECT PRODUCT_ID, COUNT(*) AS TOTAL_BATCHES
FROM PRODUCT_BATCH
GROUP BY PRODUCT_ID
HAVING COUNT(*) > (
    SELECT AVG(BATCH_COUNT)
    FROM (
        SELECT COUNT(*) AS BATCH_COUNT
        FROM PRODUCT_BATCH
        GROUP BY PRODUCT_ID
    )
);

SELECT PRODUCT_NAME
FROM PHARMACEUTICAL_PRODUCT P
WHERE EXISTS (
    SELECT 1
    FROM PRODUCT_BATCH B
    WHERE B.PRODUCT_ID = P.PRODUCT_ID
);

SELECT B.BATCH_NUMBER, B.EXPIRY_DATE
FROM PRODUCT_BATCH B
WHERE B.EXPIRY_DATE = (
    SELECT MIN(B2.EXPIRY_DATE)
    FROM PRODUCT_BATCH B2
    WHERE B2.PRODUCT_ID = B.PRODUCT_ID
);

SELECT TRANSACTION_ID, INVENTORY_ID, TRANSACTION_TYPE,
       QUANTITY, TRANSACTION_DATE, PERFORMED_BY
FROM INVENTORY_TRANSACTION
ORDER BY TRANSACTION_DATE DESC;

SELECT R.ROUTE_ID, R.ORIGIN, R.DESTINATION,
       RS.STOP_NAME, RS.SEQUENCE_NUMBER
FROM ROUTE R
JOIN ROUTE_STOP RS ON R.ROUTE_ID = RS.ROUTE_ID
ORDER BY R.ROUTE_ID, RS.SEQUENCE_NUMBER;

SELECT P.PRODUCT_NAME, SC.MINIMUM_TEMPERATURE,
       SC.MAXIMUM_TEMPERATURE, SC.STORAGE_INSTRUCTIONS
FROM PHARMACEUTICAL_PRODUCT P
JOIN STORAGE_CONDITION SC ON P.PRODUCT_ID = SC.PRODUCT_ID;

SELECT SEVERITY, COUNT(*) AS TOTAL_ALERTS
FROM TEMPERATURE_ALERT
GROUP BY SEVERITY
ORDER BY TOTAL_ALERTS DESC;

SELECT INCIDENT_ID, INCIDENT_TYPE, DESCRIPTION, RESOLUTION_STATUS
FROM COLD_CHAIN_INCIDENT
WHERE RESOLUTION_STATUS <> 'Resolved';

SELECT V.VEHICLE_ID, V.REGISTRATION_NUMBER,
       COUNT(S.SENSOR_ID) AS TOTAL_SENSORS
FROM VEHICLE V
LEFT JOIN IOT_SENSOR S ON V.VEHICLE_ID = S.VEHICLE_ID
GROUP BY V.VEHICLE_ID, V.REGISTRATION_NUMBER;

SELECT P.PRODUCT_NAME,
       SUM(I.QUANTITY_AVAILABLE) AS TOTAL_AVAILABLE,
       SUM(I.QUANTITY_RESERVED) AS TOTAL_RESERVED
FROM PHARMACEUTICAL_PRODUCT P
JOIN PRODUCT_BATCH B ON P.PRODUCT_ID = B.PRODUCT_ID
JOIN INVENTORY I ON B.BATCH_ID = I.BATCH_ID
GROUP BY P.PRODUCT_NAME;

SELECT SHIPMENT_STATUS, COUNT(*) AS TOTAL_SHIPMENTS
FROM SHIPMENT
GROUP BY SHIPMENT_STATUS;

SELECT SENSOR_ID, ROUND(AVG(TEMPERATURE), 2) AS AVG_TEMPERATURE,
       MAX(TEMPERATURE) AS MAX_TEMPERATURE,
       MIN(TEMPERATURE) AS MIN_TEMPERATURE
FROM SENSOR_READING
GROUP BY SENSOR_ID;

SELECT B.BATCH_NUMBER, P.PRODUCT_NAME,
       I.QUANTITY_AVAILABLE
FROM PRODUCT_BATCH B
JOIN PHARMACEUTICAL_PRODUCT P ON B.PRODUCT_ID = P.PRODUCT_ID
JOIN INVENTORY I ON B.BATCH_ID = I.BATCH_ID
WHERE I.QUANTITY_AVAILABLE < (
    SELECT AVG(QUANTITY_AVAILABLE)
    FROM INVENTORY
);

SELECT PRODUCT_NAME
FROM PHARMACEUTICAL_PRODUCT
WHERE PRODUCT_ID IN (
    SELECT PRODUCT_ID
    FROM PRODUCT_BATCH
    WHERE QUALITY_STATUS = 'Passed'
);

SELECT *
FROM TEMPERATURE_ALERT
WHERE ALERT_STATUS = 'Open'
AND SEVERITY = 'High';

SELECT *
FROM DELIVERY
WHERE DELIVERY_STATUS = 'Pending'
ORDER BY DELIVERY_DATE;

SELECT *
FROM QUALITY_TEST
WHERE TEST_RESULT = 'Pending'
ORDER BY TEST_DATE DESC;

SELECT W.WAREHOUSE_NAME,
       COUNT(I.INVENTORY_ID) AS INVENTORY_RECORDS,
       SUM(I.QUANTITY_AVAILABLE) AS TOTAL_QUANTITY
FROM WAREHOUSE W
JOIN STORAGE_UNIT S ON W.WAREHOUSE_ID = S.WAREHOUSE_ID
JOIN INVENTORY I ON S.STORAGE_UNIT_ID = I.STORAGE_UNIT_ID
GROUP BY W.WAREHOUSE_NAME
ORDER BY TOTAL_QUANTITY DESC;